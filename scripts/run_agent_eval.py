"""Runs the what-if agent on evals/agent_questions.jsonl, grades every answer deterministically, and writes
docs/AGENT_EVAL.md plus the raw runs (evals/runs-<model>.jsonl) for audit.

  uv run --extra agent python scripts/run_agent_eval.py [--model claude-sonnet-5-5] [--limit 5]

Needs an Anthropic API key (ANTHROPIC_API_KEY, or `ant auth login`) and spends API credit: about 40 questions, a few thousand
tokens each. The report states the measured token usage and cost. Use --limit to try a few questions first."""
import argparse
import datetime
import json
import sys
from pathlib import Path

from pitwall.agent import DEFAULT_MODEL, run_agent
from pitwall.agent_eval import grade_case, load_cases, summarise
from pitwall.agent_tools import load_context

CASES = Path("evals/agent_questions.jsonl")


def report(model, summary, graded, runs, cases):
    lines = [f"# What-if agent evaluation: {model}", "",
             f"Generated by `scripts/run_agent_eval.py` on {datetime.date.today()}. Questions: `evals/agent_questions.jsonl`. "
             "Grading is deterministic (no model as judge): `src/pitwall/agent_eval.py`. Raw runs: "
             f"`evals/runs-{model}.jsonl`.", "",
             f"**{summary['passed']} of {summary['cases']} questions passed ({summary['pass_rate']:.0%}).** "
             f"{summary['tool_calls_per_case']:.1f} tool calls per question; {summary['input_tokens']:,} input and "
             f"{summary['output_tokens']:,} output tokens"
             + (f", about ${summary['cost_usd']:.2f} at list prices." if summary["cost_usd"] is not None else "."), "",
             "| Group | Passed |", "|---|---:|"]
    lines += [f"| {g} | {v['passed']} of {v['cases']} |" for g, v in summary["by_group"].items()]
    lines += ["", "| Check | Passed |", "|---|---:|"]
    lines += [f"| {c} | {v['passed']} of {v['cases']} |" for c, v in summary["by_check"].items()]
    failures = [(g, r, c) for g, r, c in zip(graded, runs, cases) if not g["passed"]]
    lines += ["", f"## Failures ({len(failures)})", ""]
    for g, r, c in failures:
        lines += [f"**{g['id']}**: {c['question']}", "",
                  f"- problems: {'; '.join(g['problems'])}",
                  f"- tool calls: {[(t['name'], t['input']) for t in r['tool_calls']]}",
                  f"- answer: {(r['answer'] or '(none; ' + r['stop_reason'] + ')')[:500]}", ""]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--model", default=DEFAULT_MODEL)
    parser.add_argument("--limit", type=int, default=None, help="only the first N questions")
    parser.add_argument("--effort", default="medium")
    args = parser.parse_args()
    try:
        import anthropic
    except ImportError:
        sys.exit("The anthropic package isn't installed. Run: uv sync --extra agent")
    client = anthropic.Anthropic()
    ctx = load_context()
    cases = load_cases(CASES)[: args.limit]
    runs, graded = [], []
    for i, case in enumerate(cases, 1):
        try:
            run = run_agent(case["question"], ctx, client, model=args.model, effort=args.effort)
        except TypeError as error:      # the SDK raises TypeError on the first request when it finds no credentials
            if "authentication" not in str(error):
                raise
            sys.exit("No Anthropic credentials found: export ANTHROPIC_API_KEY=..., or run `ant auth login`.")
        except anthropic.AuthenticationError:
            sys.exit("Authentication failed: check ANTHROPIC_API_KEY, or run `ant auth login`.")
        except anthropic.APIError as error:
            run = {"answer": "", "tool_calls": [], "stop_reason": f"error: {type(error).__name__}", "turns": 0,
                   "usage": {"input_tokens": 0, "output_tokens": 0}}
        runs.append(run)
        graded.append(grade_case(case, run, ctx))
        print(f"{i:>2}/{len(cases)} {case['id']:<10} {'pass' if graded[-1]['passed'] else 'FAIL'}  {graded[-1]['problems'][:2]}", flush=True)
    summary = summarise(graded, runs, args.model)
    Path(f"evals/runs-{args.model}.jsonl").write_text(
        "\n".join(json.dumps({"case": c, "run": r, "graded": g}, ensure_ascii=False) for c, r, g in zip(cases, runs, graded)) + "\n",
        encoding="utf-8")
    Path("docs/AGENT_EVAL.md").write_text(report(args.model, summary, graded, runs, cases), encoding="utf-8")
    print(f"\n{summary['passed']}/{summary['cases']} passed; cost about ${summary['cost_usd']}; wrote docs/AGENT_EVAL.md")


if __name__ == "__main__":
    main()
