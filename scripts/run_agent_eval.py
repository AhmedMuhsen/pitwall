"""Runs the what-if agent on evals/agent_questions.jsonl, grades every answer deterministically, and writes
docs/AGENT_EVAL.md plus the raw runs (evals/runs-<model>.jsonl) for audit. Uses OpenRouter by default.

  export OPENROUTER_API_KEY=sk-or-...
  uv run python scripts/run_agent_eval.py --limit 5 --max-cost 0.50          # a first look, spend capped
  uv run python scripts/run_agent_eval.py --model anthropic/claude-haiku-5.5   # all 40 questions with the cheap model
  uv run python scripts/run_agent_eval.py                                      # all 40 with Sonnet 5.5

It spends real credit (OpenRouter reports the cost of each call, and the report states the total). --max-cost stops the run
between questions once that much has been spent."""
import argparse
import datetime
import json
import sys
from pathlib import Path

from pitwall.agent import DEFAULT_MODELS, run_agent
from pitwall.agent_eval import grade_case, load_cases, summarise
from pitwall.agent_tools import load_context
from pitwall.llm import AuthenticationFailed, LLMError, OutOfCredits, make_client

CASES = Path("evals/agent_questions.jsonl")


def report(model, safe, summary, graded, runs, cases):
    lines = [f"# What-if agent evaluation: {model}", "",
             f"Generated by `scripts/run_agent_eval.py` on {datetime.date.today()}. Questions: `evals/agent_questions.jsonl`. "
             "Grading is deterministic (no model as judge): `src/pitwall/agent_eval.py`. Raw runs: "
             f"`evals/runs-{safe}.jsonl`.", "",
             f"**{summary['passed']} of {summary['cases']} questions passed ({summary['pass_rate']:.0%}).** "
             f"{summary['tool_calls_per_case']:.1f} tool calls per question; {summary['input_tokens']:,} input and "
             f"{summary['output_tokens']:,} output tokens"
             + (f", cost ${summary['cost_usd']:.3f} (as billed by the provider when it reports cost, else estimated from list prices)."
               if summary["cost_usd"] is not None else "."), "",
             "| Group | Passed |", "|---|---:|"]
    lines += [f"| {g} | {v['passed']} of {v['cases']} |" for g, v in summary["by_group"].items()]
    lines += ["", "| Check | Passed |", "|---|---:|"]
    lines += [f"| {c} | {v['passed']} of {v['cases']} |" for c, v in summary["by_check"].items()]
    failures = [(g, r, c) for g, r, c in zip(graded, runs, cases) if not g["passed"]]
    lines += ["", f"## Failures ({len(failures)})", ""]
    for g, r, c in failures:
        lines += [f"**{g['id']}**: {c['question']}", "",
                  f"- problems: {'; '.join(g['problems'])}",
                  f"- tool calls: {[(t['name'], t['input']) for t in r['tool_calls']]}",
                  f"- answer: {(r['answer'] or '(none; ' + r['stop_reason'] + ')')[:500]}", ""]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--provider", choices=["openrouter", "anthropic"], default="openrouter")
    parser.add_argument("--model", default=None, help="model id in the provider's naming (default: Sonnet 5.5)")
    parser.add_argument("--limit", type=int, default=None, help="only the first N questions")
    parser.add_argument("--effort", default="medium", help="reasoning effort (used by the anthropic provider only)")
    parser.add_argument("--max-cost", type=float, default=None,
                        help="stop before the next question once the reported spend reaches this many dollars (OpenRouter reports cost per call)")
    parser.add_argument("--out", default="docs/AGENT_EVAL.md", help="where to write the report")
    args = parser.parse_args()
    model = args.model or DEFAULT_MODELS[args.provider]
    client = make_client(args.provider)
    ctx = load_context()
    cases = load_cases(CASES)[: args.limit]
    runs, graded, spent = [], [], 0.0
    for i, case in enumerate(cases, 1):
        if args.max_cost is not None and spent >= args.max_cost:
            print(f"stopping before question {i}: spent ${spent:.3f}, limit ${args.max_cost:.2f}")
            break
        try:
            run = run_agent(case["question"], ctx, client, model=model, effort=args.effort)
        except (OutOfCredits, AuthenticationFailed) as error:
            print(f"stopping before the report: {type(error).__name__}: {error}")
            break
        except LLMError as error:       # transient trouble that survived the retries: record it and go on
            run = {"answer": "", "tool_calls": [], "stop_reason": f"error: {error}"[:120], "turns": 0,
                   "usage": {"input_tokens": 0, "output_tokens": 0, "cost_usd": None}}
        spent += run["usage"]["cost_usd"] or 0.0
        runs.append(run)
        graded.append(grade_case(case, run, ctx))
        print(f"{i:>2}/{len(cases)} {case['id']:<10} {'pass' if graded[-1]['passed'] else 'FAIL'}  spent ${spent:.3f}  {graded[-1]['problems'][:2]}", flush=True)
    if not runs:
        sys.exit("No question was answered, so there is nothing to report.")
    cases = cases[: len(runs)]
    summary = summarise(graded, runs, model)
    safe = model.replace("/", "_")
    Path(f"evals/runs-{safe}.jsonl").write_text(
        "\n".join(json.dumps({"case": c, "run": r, "graded": g}, ensure_ascii=False) for c, r, g in zip(cases, runs, graded)) + "\n",
        encoding="utf-8")
    Path(args.out).write_text(report(model, safe, summary, graded, runs, cases), encoding="utf-8")
    print(f"\n{summary['passed']}/{summary['cases']} passed; cost {summary['cost_usd']}; wrote {args.out}")


if __name__ == "__main__":
    main()
