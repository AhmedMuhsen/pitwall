"""Builds data/processed/lap_dataset.parquet from the cached OpenF1 data of every Grand Prix in 2023-2025
(fetch_races.py first), leaving out races the simulator can't represent, and writes two reports:
docs/DATA_QUALITY.md (counts per included race) and docs/RACE_SELECTION.md (every race, included or not, and why)."""
import json
from collections import Counter
from pathlib import Path

import pyarrow as pa
import pyarrow.parquet as pq

from pitwall.ingestion import load_or_fetch, race_sessions
from pitwall.processing import (
    build_race_rows,
    keep_dataset_columns,
    quality_markdown,
    race_exclusion_reasons,
    race_quality,
)

OUTPUT_PATH = Path("data/processed/lap_dataset.parquet")
REPORT_PATH = Path("docs/DATA_QUALITY.md")
SELECTION_PATH = Path("docs/RACE_SELECTION.md")
SELECTION_JSON_PATH = Path("data/processed/race_selection.json")
# A race where more than this share of laps has no stint (so no compound or tyre age) is left out.
MAX_MISSING_STINT_SHARE = 0.05


def selection_markdown(selection: list[dict]) -> str:
    included = [s for s in selection if not s["reasons"]]
    reasons = Counter(reason.split(":")[0] for s in selection for reason in s["reasons"])
    lines = ["# Race selection", "",
             "Generated by `scripts/build_dataset.py`. Do not edit by hand.", "",
             f"OpenF1 lists {len(selection)} Grands Prix in 2023-2025 (it has no data before 2023; the cancelled 2023 "
             f"Emilia Romagna GP is not counted). {len(included)} are used.", "",
             "A race is left out if: it had a red flag before the chequered flag (free tyre change and standing "
             "restart, not modelled); any car ran an intermediate or wet tyre (the simulator is dry-only); "
             f"more than {MAX_MISSING_STINT_SHARE:.0%} of its laps have no stint data; or no data came back. "
             "Safety cars and virtual safety cars do not exclude a race: they are replayed.", "",
             "Reasons (a race can have more than one): " + ", ".join(f"{k} {v}" for k, v in sorted(reasons.items())), "",
             "| Race | Date | Laps in dataset | Used | Reason |", "|---|---|---:|---|---|"]
    for s in selection:
        lines.append(f"| {s['circuit']} {s['year']} | {s['date'][:10]} | {s['rows']} | "
                     f"{'yes' if not s['reasons'] else 'no'} | {', '.join(s['reasons'])} |")
    return "\n".join(lines) + "\n"


def main():
    all_rows, report, selection = [], {}, []
    for race in race_sessions():
        session_key, circuit, year = race["session_key"], race["circuit"], race["year"]
        laps = load_or_fetch("laps", session_key)
        stints = load_or_fetch("stints", session_key)
        race_control = load_or_fetch("race_control", session_key)
        reasons = race_exclusion_reasons(stints, race_control)
        rows = []
        if not laps:
            reasons.append("no_data")
        if not reasons:
            try:
                rows = keep_dataset_columns(build_race_rows(laps, stints, race_control, circuit, year))
            except ValueError as error:
                reasons.append(f"processing_error: {error}")
        if rows:
            missing = sum(1 for row in rows if row["stint_number"] is None) / len(rows)
            if missing > MAX_MISSING_STINT_SHARE:
                reasons.append(f"missing_stint_data: {missing:.0%} of laps")
        selection.append({**race, "reasons": reasons, "rows": len(rows) if not reasons else 0})
        print(f"{circuit} {year}: {'used' if not reasons else 'left out: ' + '; '.join(reasons)}", flush=True)
        if not reasons:
            report[f"{circuit} {year}"] = race_quality(rows)
            all_rows.extend(rows)

    for total_year in sorted({row["year"] for row in all_rows}):
        report[f"All {total_year}"] = race_quality([row for row in all_rows if row["year"] == total_year])
    report["All races"] = race_quality(all_rows)

    pq.write_table(pa.Table.from_pylist(all_rows), OUTPUT_PATH)
    if pq.read_table(OUTPUT_PATH).to_pylist() != all_rows:
        raise ValueError(f"{OUTPUT_PATH} does not match the rows that were written")
    print(f"Wrote {len(all_rows)} rows to {OUTPUT_PATH}")

    REPORT_PATH.write_text(quality_markdown(report), encoding="utf-8")
    SELECTION_PATH.write_text(selection_markdown(selection), encoding="utf-8")
    SELECTION_JSON_PATH.write_text(json.dumps(
        {f"{s['circuit']} {s['year']}": {"used": not s["reasons"], "reasons": [r.split(":")[0] for r in s["reasons"]]}
         for s in selection}, indent=1), encoding="utf-8")
    print(f"Wrote {REPORT_PATH} and {SELECTION_PATH}")


if __name__ == "__main__":
    main()
